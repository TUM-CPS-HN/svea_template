"""Arc-length parametrised route built from a list of waypoints.

The planner works in one dimension (arc length ``s``), the vehicle lives in
``(x, y)``. :class:`Route` is the bridge between the two:

* corners of the waypoint polyline are rounded with circular fillets, so the
  path has a finite curvature everywhere (pure pursuit tracks it better and we
  get a meaningful curvature-based speed limit for the bonus task),
* the path is resampled uniformly in ``s``,
* ``xy(s)``, ``yaw(s)``, ``curvature(s)`` and ``project(x, y)`` map between
  the two worlds, and closed routes (laps) wrap around transparently.

:class:`RouteProgress` keeps track of an *unrolled* arc length for closed
routes, i.e. ``s`` keeps growing lap after lap so that "the light is 3 m ahead"
stays well defined across the start/finish line.
"""

from __future__ import annotations

import math

import numpy as np

__all__ = ["Route", "RouteProgress"]


class Route:
    """Uniformly sampled, filleted path through ``points``.

    Args:
        points: ``(N, 2)`` waypoints in the map frame.
        closed: if True the last waypoint connects back to the first (laps).
        fillet_radius: radius used to round corners [m]. Automatically reduced
            where segments are too short to fit it.
        ds: resampling resolution [m].
    """

    def __init__(self, points, closed: bool = False, fillet_radius: float = 1.0, ds: float = 0.05):
        pts = np.asarray(points, dtype=float).reshape(-1, 2)
        # drop consecutive duplicates
        keep = np.r_[True, np.linalg.norm(np.diff(pts, axis=0), axis=1) > 1e-6]
        pts = pts[keep]
        if closed and np.linalg.norm(pts[0] - pts[-1]) < 1e-6:
            pts = pts[:-1]
        if len(pts) < 2:
            raise ValueError("A route needs at least two distinct points")

        self.closed = closed
        self.waypoints = pts
        self.ds = ds

        dense = self._fillet(pts, closed, fillet_radius)
        self.x, self.y, self.s = self._resample(dense, ds)
        self.length = float(self.s[-1])

        # heading and curvature from the dense samples
        dx = np.gradient(self.x, self.s)
        dy = np.gradient(self.y, self.s)
        self.yaw_arr = np.unwrap(np.arctan2(dy, dx))
        kappa = np.gradient(self.yaw_arr, self.s)
        # light smoothing to remove resampling noise
        w = max(1, int(round(0.15 / ds)))
        kernel = np.ones(2 * w + 1) / (2 * w + 1)
        mode = "wrap" if closed else "edge"
        self.kappa = np.convolve(np.pad(kappa, w, mode=mode), kernel, mode="valid")

    # ------------------------------------------------------------------ build

    @staticmethod
    def _fillet(pts: np.ndarray, closed: bool, radius: float) -> np.ndarray:
        n = len(pts)
        corners = range(n) if closed else range(1, n - 1)
        seg_len = lambda i, j: float(np.linalg.norm(pts[j % n] - pts[i % n]))  # noqa: E731

        out: list[np.ndarray] = []
        if not closed:
            out.append(pts[0])
        for i in corners:
            p_prev, p, p_next = pts[(i - 1) % n], pts[i], pts[(i + 1) % n]
            u1 = (p - p_prev) / np.linalg.norm(p - p_prev)
            u2 = (p_next - p) / np.linalg.norm(p_next - p)
            turn = math.atan2(u1[0] * u2[1] - u1[1] * u2[0], float(np.dot(u1, u2)))
            if abs(turn) < 1e-3 or radius <= 0:
                out.append(p)
                continue
            # tangent length, limited to 45% of the adjacent segments
            t = radius * math.tan(abs(turn) / 2)
            t_max = 0.45 * min(seg_len(i - 1, i), seg_len(i, i + 1))
            t = min(t, t_max)
            r = t / math.tan(abs(turn) / 2)
            a, b = p - u1 * t, p + u2 * t
            # centre of the arc lies on the inner side of the corner
            nrm = np.array([-u1[1], u1[0]]) * math.copysign(1.0, turn)
            c = a + nrm * r
            th0 = math.atan2(a[1] - c[1], a[0] - c[0])
            n_arc = max(4, int(abs(turn) * r / 0.02))
            for k in range(n_arc + 1):
                th = th0 + turn * k / n_arc
                out.append(c + r * np.array([math.cos(th), math.sin(th)]))
            del b  # end of arc == b, generated by the loop
        if closed:
            out.append(out[0])
        else:
            out.append(pts[-1])
        return np.asarray(out)

    @staticmethod
    def _resample(dense: np.ndarray, ds: float):
        seg = np.linalg.norm(np.diff(dense, axis=0), axis=1)
        keep = np.r_[True, seg > 1e-9]
        dense = dense[keep]
        s_raw = np.r_[0.0, np.cumsum(np.linalg.norm(np.diff(dense, axis=0), axis=1))]
        n = max(2, int(math.ceil(s_raw[-1] / ds)) + 1)
        s = np.linspace(0.0, s_raw[-1], n)
        return np.interp(s, s_raw, dense[:, 0]), np.interp(s, s_raw, dense[:, 1]), s

    # ---------------------------------------------------------------- queries

    def _wrap(self, s):
        s = np.asarray(s, dtype=float)
        if self.closed:
            return np.mod(s, self.length)
        return np.clip(s, 0.0, self.length)

    def xy(self, s):
        sw = self._wrap(s)
        return np.interp(sw, self.s, self.x), np.interp(sw, self.s, self.y)

    def yaw(self, s):
        sw = self._wrap(s)
        return np.interp(sw, self.s, self.yaw_arr)

    def curvature(self, s):
        return np.interp(self._wrap(s), self.s, self.kappa)

    def speed_limit(self, s, v_max: float, a_lat_max: float):
        """Curvature speed limit ``min(v_max, sqrt(a_lat / |kappa|))``."""
        k = np.abs(self.curvature(s))
        with np.errstate(divide="ignore"):
            v_curve = np.sqrt(a_lat_max / np.maximum(k, 1e-9))
        return np.minimum(v_max, v_curve)

    def project(self, x: float, y: float, s_hint: float | None = None, window: float = 3.0):
        """Closest point on the route.

        Args:
            x, y: query position.
            s_hint: previous arc length (any lap for closed routes). When given,
                only ``[s_hint - window, s_hint + window]`` is searched which
                avoids jumping between nearby parallel corridor legs.
            window: search half-width around the hint [m].

        Returns:
            ``(s, lateral_error)`` where ``s`` is in ``[0, length)`` (closed) or
            ``[0, length]`` (open) and the lateral error is signed (left > 0).
        """
        if s_hint is None:
            idx = np.arange(len(self.s))
        else:
            k0 = int(round(float(self._wrap(s_hint)) / self.ds))
            w = int(math.ceil(window / self.ds))
            idx = np.arange(k0 - w, k0 + w + 1)
            idx = np.mod(idx, len(self.s)) if self.closed else idx[(idx >= 0) & (idx < len(self.s))]
        d2 = (self.x[idx] - x) ** 2 + (self.y[idx] - y) ** 2
        i = int(idx[int(np.argmin(d2))])
        yaw = self.yaw_arr[i]
        ex, ey = x - self.x[i], y - self.y[i]
        # refine along the local tangent
        along = ex * math.cos(yaw) + ey * math.sin(yaw)
        lat = -ex * math.sin(yaw) + ey * math.cos(yaw)
        s = self.s[i] + along
        s = float(self._wrap(s))
        return s, float(lat)

    def lookahead_point(self, s: float, distance: float):
        x, y = self.xy(s + distance)
        return float(x), float(y)


class RouteProgress:
    """Tracks an unrolled arc length along a (possibly closed) route."""

    def __init__(self, route: Route, window: float = 3.0):
        self.route = route
        self.window = window
        self.s: float | None = None

    def reset(self, s: float | None = None):
        self.s = s

    def update(self, x: float, y: float) -> float:
        r = self.route
        s_local, _ = r.project(x, y, None if self.s is None else self.s, self.window)
        if self.s is None:
            self.s = s_local
            return self.s
        if r.closed:
            lap = math.floor(self.s / r.length)
            candidates = [s_local + (lap + k) * r.length for k in (-1, 0, 1)]
            self.s = min(candidates, key=lambda c: abs(c - self.s))
        else:
            self.s = s_local
        return self.s
